/** Verify regenerated reference output before emitting the deployment manifest. */
import { createHash } from 'node:crypto'
import { mkdtemp, readFile, readdir, rm, writeFile, mkdir } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildReferenceData } from './build-reference-data.mjs'
import { canonicalDatasetContent, referenceAssets, referenceManifestSchemaVersion, maxReferenceAssetBytes } from '../src/data/referenceManifest.ts'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const publicDirectory = resolve(root, 'public/reference-data')
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex')

async function writeManifestArtifacts(manifest, committedDirectory) {
  await mkdir(resolve(root, 'src/generated'), { recursive: true })
  await writeFile(resolve(committedDirectory, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
  await writeFile(resolve(root, 'src/generated/referenceDataset.ts'), `/** Generated by verify-reference-deployment.mjs. */\nexport const expectedReferenceDatasetId = '${manifest.datasetId}'\n`)
}

/** The explicit generation workflow calls this after the canonical generator. */
export async function generateReferenceManifest({ committedDirectory = publicDirectory, writeArtifacts = true } = {}) {
  const names = referenceAssets.map(([path]) => path)
  const actualNames = (await readdir(committedDirectory)).filter((name) => name.endsWith('.json') && name !== 'manifest.json')
  if (actualNames.length !== names.length || actualNames.some((name) => !names.includes(name))) {
    throw new Error('Committed reference-data inventory differs from the 13-file allowlist.')
  }
  const assets = []
  for (const path of names) {
    const committed = await readFile(resolve(committedDirectory, path))
    if (committed.length > maxReferenceAssetBytes) throw new Error(`${path} exceeds the asset size limit.`)
    const parsed = JSON.parse(committed.toString('utf8'))
    if (!Array.isArray(parsed)) throw new Error(`${path} must contain a JSON array.`)
    assets.push({ path, sha256: digest(committed) })
  }
  const datasetId = `sha256:${digest(canonicalDatasetContent(assets))}`
  const manifest = { schemaVersion: referenceManifestSchemaVersion, datasetId, assets }
  if (writeArtifacts) await writeManifestArtifacts(manifest, committedDirectory)
  return manifest
}

export async function verifyReferenceDeployment({ committedDirectory = publicDirectory, expectedDirectory, writeArtifacts = true } = {}) {
  const temporaryDirectory = expectedDirectory ?? await mkdtemp(resolve(tmpdir(), 'starfield-reference-'))
  try {
    if (!expectedDirectory) await buildReferenceData(temporaryDirectory)
    const manifest = await generateReferenceManifest({ committedDirectory, writeArtifacts: false })
    for (const { path } of manifest.assets) {
      const [expected, committed] = await Promise.all([
        readFile(resolve(temporaryDirectory, path)),
        readFile(resolve(committedDirectory, path)),
      ])
      if (!expected.equals(committed)) throw new Error(`${path} differs from generated reference data. Run npm run reference:build intentionally.`)
    }
    if (writeArtifacts) await writeManifestArtifacts(manifest, committedDirectory)
    return manifest
  } finally {
    if (!expectedDirectory) await rm(temporaryDirectory, { recursive: true, force: true })
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  verifyReferenceDeployment().catch((error) => {
    console.error(error instanceof Error ? error.message : error)
    process.exitCode = 1
  })
}
